CREATE TABLE IF NOT EXISTS subscribers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 subscriber_id VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 sms_destination VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'INACTIVE',
 stopped BOOLEAN NOT NULL DEFAULT FALSE,
 event_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
);
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 subscriber_id BIGINT UNSIGNED NOT NULL,
 billing_day DATE NOT NULL,
 external_trx_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 amount DECIMAL(12,2) NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'XTS',
 state VARCHAR(24) NOT NULL DEFAULT 'PENDING',
 attempt_count INT NOT NULL DEFAULT 0,
 next_attempt_at DATETIME(6) NULL,
 reference_id VARCHAR(160) NULL,
 last_code VARCHAR(40) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 UNIQUE KEY one_charge_per_day (subscriber_id, billing_day),
 FOREIGN KEY (subscriber_id) REFERENCES subscribers(id)
);
CREATE TABLE IF NOT EXISTS charge_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 payment_id BIGINT UNSIGNED NOT NULL,
 attempt_number INT NOT NULL,
 external_trx_id CHAR(64) NOT NULL,
 status_code VARCHAR(40) NOT NULL DEFAULT 'PROCESSING',
 reference_id VARCHAR(160) NULL,
 started_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 finished_at DATETIME(6) NULL,
 UNIQUE KEY one_attempt (payment_id, attempt_number),
 FOREIGN KEY (payment_id) REFERENCES payments(id)
);
CREATE TABLE IF NOT EXISTS webhook_events (
 fingerprint CHAR(64) PRIMARY KEY,
 subscriber_id VARCHAR(160) NOT NULL,
 status VARCHAR(20) NOT NULL,
 event_at DATETIME(6) NOT NULL,
 received_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);
CREATE TABLE IF NOT EXISTS sms_outbox (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 subscriber_id BIGINT UNSIGNED NOT NULL,
 dedupe_key VARCHAR(160) NOT NULL UNIQUE,
 kind VARCHAR(20) NOT NULL,
 message TEXT NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 attempts INT NOT NULL DEFAULT 0,
 next_attempt_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY (subscriber_id) REFERENCES subscribers(id)
);
